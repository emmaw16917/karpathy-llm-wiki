class ConvertTest(unittest.TestCase):
    def setUp(self):
        self.result = convert(PAGE, base_url="https://arxiv.org/html/1234.5678v2/")
        self.md = self.result.markdown

    def test_drops_site_chrome_and_toc(self):
        for text in ("SITE HEADER", "TOC ENTRY", "GENERATED BY", "SECRET AFFILIATION"):
            self.assertNotIn(text, self.md)

    def test_math_comes_from_alttext_and_is_unescaped(self):
        self.assertIn("$Q_{i}<1$", self.md)
        self.assertNotIn("WRONG", self.md)

    def test_display_equation_keeps_number(self):
        self.assertIn("$$\nE=mc^{2} \\tag{1}\n$$", self.md)

    def test_table_keeps_merged_cells_and_values(self):
        self.assertIn('<th rowspan="2">M</th>', self.md)
        self.assertIn('<th colspan="2">V</th>', self.md)
        self.assertIn("<td>0.9712</td>", self.md)
        self.assertIn("<td>$\\alpha$</td>", self.md)
        self.assertIn("Table 1: Scores.", self.md)

    def test_heading_and_inline_formatting(self):
        self.assertIn("## 1 Intro", self.md)
        self.assertIn("*good*", self.md)
        self.assertIn("(Albert, 2023)", self.md)
        self.assertNotIn("#bib.bib1", self.md)
        self.assertIn("[site](https://example.com/x)", self.md)

    def test_image_url_is_absolute_with_caption(self):
        self.assertIn("![Figure 1: Flow.](https://arxiv.org/html/1234.5678v2/x1.png)", self.md)

    def test_listing_lines_stay_separate(self):
        self.assertRegex(self.md, r"1: init \$k=0\$ *\n+2: stop")

    def test_footnote_inline_once(self):
        self.assertEqual(self.md.count("Footnote body."), 1)

    def test_bibliography_and_authors(self):
        self.assertIn("Ada Lovelace", self.md)
        self.assertRegex(self.md, r"- \[Albert \(2023\)\] Alex Albert\. +Jailbreak chat, 2023\.")

    def test_counts_and_title(self):
        self.assertEqual(self.result.title, "My Paper")
        self.assertEqual(self.result.errors, 0)
        self.assertNotIn("# My Paper", self.md)

    def test_latexml_errors_are_counted(self):
        bad = PAGE.replace("Note<", '<span class="ltx_ERROR">\\foo</span>Note<')
        self.assertEqual(convert(bad, "https://x/").errors, 1)

    def test_page_without_document_is_rejected(self):
        with self.assertRaises(ValueError):
            convert("<html><body>No HTML for this paper</body></html>", "https://x/")


def item(**kw):
    base = dict(key="K", item_type="preprint", title="T", doi="", url="", archive_id="", extra="",
                date="2024", first_author="Liu")
    base.update(kw)
    return Item(**base)


class FetchHtmlTest(unittest.TestCase):
    def test_base_url_resolves_real_arxiv_image_paths(self):
        response = mock.MagicMock()
        response.__enter__.return_value.read.return_value = b"<html></html>"
        paper = arxiv.Paper("2310.04451", 2, "T", [], "")
        with mock.patch.object(arxiv, "_get", return_value=response):
            _, base = arxiv.fetch_html(paper)
        md = convert('<article class="ltx_document"><figure><img src="2310.04451v2/a.png"></figure></article>', base).markdown
        self.assertIn("https://arxiv.org/html/2310.04451v2/a.png", md)


class ArxivIdTest(unittest.TestCase):
    def test_ids_from_each_field(self):
        self.assertEqual(zotero.arxiv_id(item(doi="10.48550/arXiv.2310.04451")), "2310.04451")
        self.assertEqual(zotero.arxiv_id(item(archive_id="arXiv:2310.04451")), "2310.04451")
        self.assertEqual(zotero.arxiv_id(item(url="http://arxiv.org/abs/2310.04451v3")), "2310.04451")
        self.assertEqual(zotero.arxiv_id(item(extra="arXiv:cs/0112017 [cs]")), "cs/0112017")
        self.assertIsNone(zotero.arxiv_id(item(doi="10.14778/3594512.3594528")))


class VersionPolicyTest(unittest.TestCase):
    def paper(self, title="Great Paper: A Study", authors=("Ada Sun", "Bo Li")):
        return arxiv.Paper("2401.00001", 2, title, list(authors), "2024-01-01")

    def test_preprint_item_is_authoritative(self):
        chosen = cli.choose_arxiv(item(doi="10.48550/arXiv.2401.00001"), lookup=lambda i: self.paper(), search=None)
        self.assertEqual(chosen.note, "")

    def test_published_item_with_matching_preprint_gets_warning(self):
        it = item(item_type="journalArticle", title="Great paper - a study", first_author="Sun")
        chosen = cli.choose_arxiv(it, lookup=None, search=lambda t: [self.paper()])
        self.assertEqual(chosen.paper.arxiv_id, "2401.00001")
        self.assertIn("may differ", chosen.note)

    def test_published_item_rejects_title_or_author_mismatch(self):
        it = item(item_type="journalArticle", title="Other Paper", first_author="Sun")
        self.assertIsNone(cli.choose_arxiv(it, lookup=None, search=lambda t: [self.paper()]))
        it = item(item_type="journalArticle", title="Great Paper: A Study", first_author="Zhang")
        self.assertIsNone(cli.choose_arxiv(it, lookup=None, search=lambda t: [self.paper()]))


class WriteRawTest(unittest.TestCase):
    def run_main(self, out, html=PAGE):
        it = item(key="ABC", doi="10.48550/arXiv.2401.00001", title="Zotero Title")
        paper = arxiv.Paper("2401.00001", 2, "Great", ["Ada Liu"], "2024-01-01")
        with mock.patch.object(cli.zotero, "find", return_value=it), \
                mock.patch.object(cli.arxiv, "lookup", return_value=paper), \
                mock.patch.object(cli.arxiv, "fetch_html", return_value=(html, "https://arxiv.org/html/2401.00001v2/")):
            return cli.main(["--key", "ABC", "--out", str(out), "--config", str(out) + ".none"])

    def test_writes_raw_header_and_refuses_overwrite(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "raw" / "t" / "p.md"
            self.assertEqual(self.run_main(out), 0)
            text = out.read_text(encoding="utf-8")
            self.assertTrue(text.startswith("# My Paper\n\n> Source: https://arxiv.org/abs/2401.00001v2\n"))
            for line in ("> Published: 2024", "> Extractor: arxiv-html", "> Zotero: ABC", "> DOI: 10.48550/arXiv.2401.00001"):
                self.assertIn(line, text)
            self.assertEqual(self.run_main(out), 2)
            self.assertEqual(out.read_text(encoding="utf-8"), text)

    def test_no_html_reports_next_route_and_writes_nothing(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "p.md"
            self.assertEqual(self.run_main(out, html="<html>none</html>"), 3)
            self.assertFalse(out.exists())


